#include <iostream>
#include <iomanip>

// Лабораторная работа №2, вариант 18.
// Найти сумму ряда с точностью eps = 10^-4, общий член которого a_n = n^3 / (3n-3)!
//
// Рекуррентная формула:
//   a(n+1)/a(n) = ((n+1)^3 / n^3) * (3n-3)! / (3n)! = ((n+1)/n)^3 / ((3n-2)*(3n-1)*3n)
//   a(n+1) = a(n) * ((n+1)/n)^3 / ((3n-2)*(3n-1)*3n),   a(1) = 1^3 / 0! = 1
//
// Точность достигнута, когда a_n < eps; такой член в сумму не включается.
int main()
{
    const double eps = 1e-4;
    double a = 1.0;             // первый член ряда a1
    double s = 0.0;             // сумма
    int n = 1;                  // номер члена

    while (a >= eps)            // пока член ряда не стал меньше eps
    {
        s += a;                 // добавляем текущий член
        std::cout << "n = " << n << ",  a_n = " << std::fixed << std::setprecision(8) << a << "\n";

        double r = (n + 1.0) / n;                       // (n+1)/n
        a = a * r * r * r / ((3.0 * n - 2) * (3.0 * n - 1) * (3.0 * n));   // a(n+1)
        n++;
    }

    std::cout << "n = " << n << ",  a_n = " << a << "  < eps, останов\n\n";
    std::cout << "Сумма ряда с точностью 10^-4: S = " << std::setprecision(6) << s << "\n";
    return 0;
}
