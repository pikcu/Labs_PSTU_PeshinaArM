#include <iostream>

// 1) n++*m   2) n++<m   3) m-- >m

int main()
{
    int n0, m0;                 // введённые значения
    int n, m, r;

    std::cout << "Введите n: ";
    std::cin >> n0;
    std::cout << "Введите m: ";
    std::cin >> m0;

    // 1) n++*m : берётся старое n, затем n увеличивается на 1
    n = n0; m = m0;
    r = n++ * m;
    std::cout << "1) n++*m   = " << r << "   (после: n=" << n << ", m=" << m << ")\n";

    // 2) n++<m : сравнивается старое n с m, затем n увеличивается на 1
    n = n0; m = m0;
    r = n++ < m;
    std::cout << "2) n++<m   = " << r << "   (после: n=" << n << ", m=" << m << ")\n";

    // 3) m-- >m : слева старое значение m, справа уже уменьшенное.
    n = n0; m = m0;
    int old = m;                // значение, которое вернёт m--
    m = m - 1;                  // побочный эффект m--
    r = old > m;
    std::cout << "3) m-- >m  = " << r << "   (после: n=" << n << ", m=" << m << ")\n";

    return 0;
}
